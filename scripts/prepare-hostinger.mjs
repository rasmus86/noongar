import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const outDir = join(process.cwd(), "out");
if (!existsSync(outDir)) {
  console.error("Missing out/ — run next build with output: 'export' first.");
  process.exit(1);
}

const htaccess = `# Noongar — Hostinger static demo
Options -Indexes
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule ^ index.html [L]
</IfModule>

# Cache static assets briefly (demo)
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/css "access plus 1 hour"
  ExpiresByType application/javascript "access plus 1 hour"
  ExpiresByType image/jpeg "access plus 1 day"
  ExpiresByType image/png "access plus 1 day"
  ExpiresByType application/octet-stream "access plus 1 day"
</IfModule>
`;

writeFileSync(join(outDir, ".htaccess"), htaccess);

const deployDir = join(process.cwd(), "deploy", "hostinger");
mkdirSync(deployDir, { recursive: true });
copyFileSync(join(outDir, ".htaccess"), join(deployDir, ".htaccess"));

writeFileSync(
  join(process.cwd(), "deploy", "README.md"),
  `# Deploy Noongar to Hostinger (temporary public demo)

## What to upload
Upload **everything inside** \`out/\` into your Hostinger \`public_html/\`
(or a subdomain folder such as \`public_html/noongar/\`).

Generated by: \`npm run build:hostinger\`

## hPanel steps
1. Hostinger → **Websites** → your site → **File Manager**
2. Open \`public_html\`
3. Upload the contents of \`out/\` (including \`.htaccess\`, \`_next/\`, \`brand/\`, \`models/\`)
4. Open your domain (HTTPS). Camera needs a secure origin.

## FTP / SFTP (agent or FileZilla)
- Host: usually \`ftp.yourdomain.com\` or the IP from hPanel → FTP Accounts
- User / password: from hPanel
- Remote path: \`public_html\`
- Local path: \`out/\`

Optional one-liner after secrets are set:

\`\`\`bash
npm run build:hostinger
npx --yes basic-ftp <<'NODE'
# or use scripts/upload-hostinger.mjs with env vars
NODE
\`\`\`

Env vars expected by \`scripts/upload-hostinger.mjs\`:
- \`HOSTINGER_FTP_HOST\`
- \`HOSTINGER_FTP_USER\`
- \`HOSTINGER_FTP_PASSWORD\`
- \`HOSTINGER_FTP_REMOTE_DIR\` (default \`/public_html\`)
`,
);

console.log("Hostinger package ready in out/ (+ .htaccess). See deploy/README.md");
